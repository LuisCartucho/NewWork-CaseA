// npm run report: writes docs/sample_outputs.md from results/results.json (no AI calls).
// Generated, so the document always matches what the app shows.
import fs from "node:fs";
import path from "node:path";
import { config } from "./config.js";
import type { PipelineResult } from "./types.js";

// Easy case first, then the difficult ones, each with why it's in the list.
const PICKS: [string, string][] = [
  ["M003", "The easy case: every fact found, both sources agree."],
  ["M012", "Data disagrees with itself: the CSV weight is 5x the packed weight on the fact sheet."],
  ["M010", "Picks the right market row, and notices the colour isn't on the fact sheet it was asked to send."],
  ["M028", "A trap in the fact sheet: \"Yes\" on p.1 means \"light source included\", not \"dimmable\"."],
  ["M011", "Not in the data at all (seat height), and the email contains a number we can't confirm."],
  ["M025", "Mixed: some answered, sealing unknown, size not specified."],
  ["M029", "Only answerable from the fact sheet, and fabric categories differ per product."],
  ["M019", "Certificates: we can name what the sheet lists, but the documents aren't in the data."],
  ["M027", "Personal data and an order: redacted before anything else, routed to a person."],
];

const ICON = { green: "🟢 Green", yellow: "🟡 Yellow", red: "🔴 Red" } as const;
const results: PipelineResult[] = JSON.parse(fs.readFileSync(path.join(config.paths.results, "results.json"), "utf8"));

const quote = (text: string) => text.trim().split("\n").map((l) => `> ${l}`).join("\n");
const block = (text: string) => "```text\n" + text.trim() + "\n```";

const sections = PICKS.map(([id, why]) => {
  const r = results.find((x) => x.email.id === id);
  if (!r) throw new Error(`${id} not in results.json`);
  const products = r.resolution.matches.map((m) =>
    `${m.name}: ${m.variants.length === 1 ? `SKU ${m.variants[0].sku}` : `${m.variants.length} variants possible (${m.variants.map((p) => p.sku).join(", ")})`}`);
  return [
    `## ${id} · ${r.email.subject}`,
    `*${why}*`,
    `**From** ${r.email.from_retailer}, ${r.email.date}${r.redaction.containsPersonalData ? ` · **Personal data removed:** ${r.redaction.redactedFields.join(", ")}` : ""}`,
    quote(r.email.body),
    `**Status: ${ICON[r.status]}**`,
    r.flags.map((f) => `- ${f.level === "green" ? "🟢" : f.level === "yellow" ? "🟡" : "🔴"} ${f.reason}`).join("\n"),
    `**Product:** ${products.join("; ") || "none recognised"}`,
    r.facts.length
      ? ["**Facts found** (with source):", "", "| Fact | Value | Source |", "|---|---|---|",
        ...r.facts.map((f) => `| ${f.label.replace(/^[^:]+:\s*/, "")} | ${f.value.replace(/\|/g, "/")} | ${f.source} |`)].join("\n")
      : "**Facts found:** none",
    r.missing.length ? `**Not in our data:** ${r.missing.join("; ")}` : "",
    r.conflicts.length ? `**Sources disagree:**\n${r.conflicts.map((c) => `- ${c}`).join("\n")}` : "",
    `**Draft reply** (${r.aiUsed ? `written by ${r.ai.draft}, numbers checked against the data` : "facts only, AI unavailable"}):`,
    block(r.draft),
  ].filter(Boolean).join("\n\n");
});

const counts = { green: 0, yellow: 0, red: 0 };
for (const r of results) counts[r.status]++;

const doc = [
  "# Sample outputs",
  "",
  `Generated by \`npm run report\` from \`server/results/results.json\`: the same output the app shows. ` +
    `All 30 emails: ${counts.green} green, ${counts.yellow} yellow, ${counts.red} red ` +
    `(full list in [\`server/results/results.md\`](../server/results/results.md)). ` +
    "Below: one easy case and eight difficult ones.",
  "",
  ...PICKS.map(([id, why]) => `- **${id}**: ${why}`),
  "",
  sections.join("\n\n---\n\n"),
  "",
].join("\n");

const out = path.resolve(config.paths.data, "..", "..", "docs", "sample_outputs.md");
fs.writeFileSync(out, doc);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${PICKS.length} emails)`);
